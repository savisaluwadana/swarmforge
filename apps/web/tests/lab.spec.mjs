import {test,expect} from "@playwright/test";
test("real scenario, worker, evidence and benchmark",async({page})=>{
 await page.goto("/");await expect(page.getByRole("heading",{name:/When coordination/})).toBeVisible();await page.screenshot({path:"test-results/landing.png",fullPage:true});
 await page.getByRole("link",{name:/Enter the laboratory/}).click();
 await page.getByLabel("Access token").fill(process.env.LOCAL_DEMO_TOKEN);
 await page.getByRole("button",{name:"Connect workspace"}).click();
 await expect(page.getByRole("heading",{name:"Reliability laboratory"})).toBeVisible();
 await page.getByRole("link",{name:"+ New scenario"}).click();
 await page.getByRole("button",{name:"Validate scenario"}).click();
 await expect(page.getByText("Scenario valid",{exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Save scenario",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Launch experiment"})).toBeVisible();
 await page.screenshot({path:"test-results/studio.png",fullPage:true});
 await page.getByLabel("Execution mode").selectOption("interactive");
 await page.getByRole("button",{name:/Launch simulation/}).click();
 await expect(page.getByRole("heading",{name:"Fleet telemetry"})).toBeVisible();
 await expect(page.getByRole("button",{name:"Inject fault"})).toBeEnabled();
 await page.getByRole("button",{name:"Inject fault"}).click();
 await expect(page.getByText(/#1 packet_loss/)).toBeVisible();
 await expect(page.getByText("applied",{exact:true})).toBeVisible();
 await expect(page.getByText("Trace SHA-256:",{exact:false})).toBeVisible({timeout:60000});
 await page.screenshot({path:"test-results/run.png",fullPage:true});
 await page.getByRole("button",{name:"Replay events"}).click();
 await expect(page.getByRole("button",{name:"Play events"})).toBeVisible();
 await page.getByRole("button",{name:"Exit replay"}).click();
 const d=page.waitForEvent("download");await page.getByRole("button",{name:"Export JSON"}).click();expect((await d).suggestedFilename()).toMatch(/run-.*\.json/);
 await page.getByRole("link",{name:"Benchmark center"}).click();
 await expect(page.getByRole("heading",{name:"Compare coordination policies"})).toBeVisible();
 const scenario=page.getByRole("combobox",{name:"Scenario",exact:true});
 await expect(scenario.getByRole("option",{name:"Warehouse / controller outage",exact:true})).toBeAttached();
 await scenario.selectOption({label:"Warehouse / controller outage"});
 await expect(page.getByRole("combobox",{name:"Revision",exact:true})).toHaveValue("1");
 await page.getByLabel("Random seeds").fill("11");
 await page.getByRole("button",{name:"Launch benchmark · 3 runs"}).click();
 await expect(page.getByRole("heading",{name:"Measured policy comparison"})).toBeVisible();
 await expect(page.locator(".heading .status")).toHaveText("succeeded",{timeout:60000});
 await expect(page.getByText("Successful",{exact:true})).toBeVisible();
 await page.screenshot({path:"test-results/benchmark.png",fullPage:true});
 await page.getByRole("link",{name:"Agent console"}).click();
 await expect(page.getByRole("heading",{name:"Describe the reliability question"})).toBeVisible();
 await page.getByRole("combobox",{name:"Base scenario"}).selectOption({label:"Warehouse / controller outage"});
 await page.getByLabel("Manual random seeds").fill("11");
 await page.getByRole("button",{name:"Draft without AI"}).click();
 await expect(page.getByRole("heading",{name:"Review experiment plan"})).toBeVisible();
 await page.getByLabel("Separate human approval credential").fill(process.env.AGENT_APPROVAL_SECRET);
 await page.getByRole("button",{name:"Approve exact plan"}).click();
 await page.getByRole("button",{name:"Execute approved plan"}).click();
 await expect(page.getByRole("heading",{name:"Persisted execution handles"})).toBeVisible();
 await page.screenshot({path:"test-results/agent.png",fullPage:true});
});
